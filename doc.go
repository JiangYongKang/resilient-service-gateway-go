// Package gateway 实现本地服务调用网关，在调用方与下游实现之间提供
// 一致且可解释的熔断、并发隔离、超时（调用方总截止时间传播 +
// 按路由的单次尝试预算）与重试行为。
//
// 每次尝试的实际截止时间取 RouteConfig.AttemptBudget 与“当时剩余的调用方
// 总预算”中的更小值；调用方未给总截止时间时 AttemptBudget 单独生效。
// 每次尝试派发前都做预算预检：总截止时间已过、剩余为正但不足一次尝试
// 预算是两种不同的拒绝语义；重试链路上则分别对应 budget_exhausted 与
// budget_insufficient 两种终局。调用方未给截止时间且路由未配置任何单次
// 预算/默认超时时为不设限（unlimited），既不会被预算判定拒绝，对外也如实
// 表达为 unlimited 而不是某个具体时长。
//
// 失败语义分为两类：
//   - *RejectError：请求在派发给下游之前被拒绝（首次即截止时间过期、
//     剩余不足一次尝试、熔断打开、探测并发受限、下游并发已满），
//     可通过 RejectReason 区分原因。
//   - *TerminalError：请求已派发但得到不可重试终局（不可重试失败、
//     总预算耗尽、剩余不足下一次尝试、重试途中熔断/并发拒绝），
//     可通过 TerminalKind 区分。下游原始错误永远不会被透出。
